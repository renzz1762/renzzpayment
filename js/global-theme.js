function applyGlobalTheme(name) {
  if (!name || name === '' || name === 'default') return;
  var th = GLOBAL_THEMES[name];
  if (!th) return;
  var root = document.documentElement;
  root.setAttribute('data-global-theme', name);
  for (var k in th) {
    if (Object.prototype.hasOwnProperty.call(th, k) && k !== 'label') {
      root.style.setProperty(k, th[k]);
    }
  }
}


